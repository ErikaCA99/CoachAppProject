import os

from roboflow import Roboflow
rf = Roboflow(api_key=os.environ["ROBOFLOW_API_KEY"])
project = rf.workspace("chambita").project("custom_object_detector_yolo11-iu8za")
version = project.version(6)
dataset = version.download("yolov11")

from ultralytics import YOLO
model = YOLO('yolo11x.pt')

data_path = os.path.join(dataset.location, "data.yaml")
results = model.train(data=data_path,
                      epochs=15,
                      imgsz=640)

#COMENZAMOS A HACER LAS PREDICCIONES

#Cargamos el mejor modelo ya entrenado
custom_model = YOLO(str(model.trainer.best))

#Realizamos predicciones sobre algunas imagenes
res = custom_model(os.path.join(dataset.location, "test", "images"))

#Visualizamos los resultados de las detecciones
res[0].show()
